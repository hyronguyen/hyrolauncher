const testRuntime = require('./test-runtime.cjs'); testRuntime.prepare();
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const script = fs.readFileSync('ui/plugin.html', 'utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
let listener;
const messages = [];
const fields = { mTitle: { value: 'Test movie', focus() {} }, mPoster: { value: 'poster.jpg' }, mEpisode: { value: '3', focus() {} }, mTime: { value: '12:34' }, mUrl: { value: 'https://example.com/movie' } };
const editor = { innerHTML: '', classList: { toggle(name, show) { this.open = show; } } };
const context = { URLSearchParams, location: { search: '?id=builtin.movie-watchlist' }, chrome: { webview: { postMessage: msg => messages.push(JSON.parse(JSON.stringify(msg))), addEventListener: (name, handler) => listener = handler } }, document: { getElementById: id => id === 'movieEditor' ? editor : fields[id], documentElement: { style: { setProperty() {} }, classList: { toggle() {} } }, body: { classList: { toggle() {} } } }, app: { innerHTML: '' }, ...fields, alert: msg => { throw new Error(msg); }, confirm: () => true };
context.document.body.dataset = {};
context.app.classList = {toggle(){}};
context.appAlert = msg => { throw new Error(msg); };
context.appConfirm = async () => true;
context.uiEffects = { configure() {}, play() {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync('ui/plugin-tools.js', 'utf8'), context);
vm.runInContext(script, context);
const state = { Games: [], Plugins: [{ Id: 'builtin.movie-watchlist', Type: 'movie-watchlist', WatchItems: [], MovieWebsiteGameIds: [] }], Settings: {} };
listener({ data: { type: 'state', state } });
vm.runInContext('newWatchItem(); saveWatch()', context);
assert(editor.classList.open, 'Save must keep the editor open');
const saved = messages.find(m => m.type === 'savePlugin');
assert.equal(saved.plugin.WatchItems.length, 1);
assert.equal(saved.plugin.WatchItems[0].Title, 'Test movie');
fields.mTitle.value = 'Unsaved draft after save';
listener({ data: { type: 'state', state: { ...state, Plugins: [saved.plugin] } } });
assert(editor.classList.open, 'State refresh must keep the editor open');
assert(editor.innerHTML.includes('Unsaved draft after save'), 'State refresh must preserve the typed draft');
vm.runInContext('saveWatch()', context);
assert.equal(messages.at(-1).plugin.WatchItems.length, 1, 'Repeated save should update the item, not duplicate it');
async function checkBrowserIntegration() {
  context.browserPage={title:'Page title',url:'https://example.com/movie'};
  context.appConfirm=async()=>false;
  await vm.runInContext('receiveBrowserWatch(browserPage)',context);
  assert.equal(vm.runInContext('watchDraft.Title',context),'Unsaved draft after save','Cancelled replacement must preserve the draft');
  context.appConfirm=async()=>true;
  await vm.runInContext('receiveBrowserWatch(browserPage)',context);
  assert.equal(vm.runInContext('watchDraft.Episode',context),'3','Reopening the same URL preserves episode information');
  assert.equal(vm.runInContext('watchDraft.PosterPath',context),'poster.jpg');
  context.browserPage={title:'Another movie',url:'https://another-site.example/movie'};
  await vm.runInContext('receiveBrowserWatch(browserPage)',context);
  assert.equal(vm.runInContext('watchDraft.SourceGameId',context),'','New movies must not require a web app');
  assert.equal(vm.runInContext('watchDraft.Url',context),context.browserPage.url);
  assert(context.app.innerHTML.includes('HyBrowser'));
  assert(!context.app.innerHTML.includes('movieSitesBlock'));
  context.progressItem={Id:'progress',Title:'Series',Episode:'3',TotalEpisodes:12,Status:'watching',WatchTime:'',Url:'https://example.com/series'};
  assert.equal(vm.runInContext('movieProgress(progressItem)',context),25);
  assert.equal(vm.runInContext("movieProgress({Episode:'3'})",context),null,'Do not invent progress without a total');
  assert.equal(vm.runInContext("movieStatus({Episode:'done'})",context),'completed','Old completed entries stay completed');
  assert.equal(vm.runInContext("movieStatus({Episode:'',WatchTime:''})",context),'planned','Movies with no progress belong in My list');
  context.appConfirm=async()=>true;
  vm.runInContext('watchDraft=null;plugin().WatchItems.push(progressItem);editWatchProgress("progress")',context);
  assert(editor.innerHTML.includes('Update progress'));
  assert(!editor.innerHTML.includes('id="mTitle"'),'Quick progress editor omits title/artwork/link fields');
  // Model the actual DOM: quick progress must retain omitted fields.
  delete fields.mTitle; delete fields.mPoster; delete fields.mUrl;
  fields.mEpisode.value='4'; fields.mTime.value='20:00'; fields.mStatus={value:'watching'}; fields.mTotal={value:'12'};
  vm.runInContext('saveWatch()',context);
  const quick=messages.at(-1).plugin.WatchItems.find(item=>item.Id==='progress');
  assert.equal(quick.Title,'Series'); assert.equal(quick.Url,context.progressItem.Url); assert.equal(quick.Episode,'4'); assert.equal(quick.TotalEpisodes,12);
  fields.mEpisode.value='5';
  listener({data:{type:'state',state:{...state,Plugins:[messages.at(-1).plugin]}}});
  assert.equal(vm.runInContext('watchDraft.Episode',context),'5','State refresh preserves a quick progress draft');
  console.log('PASS: Watchlist add/save persistence, browser page prefill, protected drafts, same-URL metadata, any website without web apps');
}
checkBrowserIntegration().catch(error=>{console.error(error);process.exitCode=1;});
